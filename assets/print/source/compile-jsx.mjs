#!/usr/bin/env node
/**
 * compile-jsx.mjs — transform print-pack JSX to a single IIFE bundle.
 *
 * The production print HTML loads print-bundle.js (no Babel-in-Chrome).
 * Re-run after any *.jsx change:
 *
 *   node compile-jsx.mjs
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const files = [
  "tile-icons.jsx",
  "tile-data.jsx",
  "board-a.jsx",
  "primitives.jsx",
  "artifact-player-mat.jsx",
  "artifact-quick-ref.jsx",
  "artifact-treaty-ref.jsx",
  "artifact-cards.jsx",
  "artifact-market-board.jsx",
];

const esbuildJs = path.join(dir, "node_modules", "esbuild", "bin", "esbuild");
const npxBin = process.platform === "win32" ? "npx.cmd" : "npx";
const esbuildCmd = fs.existsSync(esbuildJs) ? process.execPath : npxBin;
const esbuildArgsPrefix = fs.existsSync(esbuildJs)
  ? [esbuildJs]
  : ["--yes", "esbuild"];

const parts = ["/* generated by compile-jsx.mjs — do not edit */", `"use strict";`];
for (const f of files) {
  const src = path.join(dir, f);
  if (!fs.existsSync(src)) {
    throw new Error(`missing JSX source: ${src}`);
  }
  const args = [
    ...esbuildArgsPrefix,
    src,
    "--bundle",
    "--format=iife",
    "--jsx=transform",
    "--jsx-factory=React.createElement",
    "--jsx-fragment=React.Fragment",
    "--target=es2018",
    "--log-level=warning",
  ];
  const code = execFileSync(esbuildCmd, args, { encoding: "utf8", cwd: dir });
  parts.push(`/* ---- ${f} ---- */`, code.trim());
}

const out = path.join(dir, "print-bundle.js");
fs.writeFileSync(out, parts.join("\n") + "\n");
console.error(`wrote ${path.relative(dir, out)} (${fs.statSync(out).size} bytes)`);
